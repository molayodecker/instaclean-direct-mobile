import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as ts from 'typescript';

const defaultSource = 'https://instaclean-mithril-staging.fly.dev/openapi.json';
const source = process.env.MITHRIL_OPENAPI_URL ?? defaultSource;
const checkOnly = process.argv.includes('--check');
const selfTest = process.argv.includes('--self-test');
const scriptDir = dirname(fileURLToPath(import.meta.url));
const target = resolve(scriptDir, '../lib/mithril/generated/mithril.ts');

function canonicalizeTypeScript(sourceText) {
  const sourceFile = ts.createSourceFile(
    'mithril.ts',
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );

  if (sourceFile.parseDiagnostics.length > 0) {
    const details = sourceFile.parseDiagnostics
      .map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'))
      .join('\n');
    throw new Error(`Could not parse generated Mithril types:\n${details}`);
  }

  const printer = ts.createPrinter({
    newLine: ts.NewLineKind.LineFeed,
    removeComments: true,
  });

  return printer.printFile(sourceFile).trim();
}

function runSelfTest() {
  const styled = `
/** Custom repository banner. */
export type paths = Record<string, never>
export interface components {
  schemas: {
    Example: {
      id: string
      metadata?: { [key: string]: unknown }
    }
  }
  responses: never
  parameters: never
  requestBodies: never
  headers: never
  pathItems: never
}
export type operations = Record<string, never>
`;

  const generated = `
/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */
export type paths = Record<string, never>;
export interface components {
    schemas: {
        Example: {
            id: string;
            metadata?: {
                [key: string]: unknown;
            };
        };
    };
    responses: never;
    parameters: never;
    requestBodies: never;
    headers: never;
    pathItems: never;
}
export type operations = Record<string, never>;
`;

  const changed = generated.replace('id: string;', 'id: number;');

  if (canonicalizeTypeScript(styled) !== canonicalizeTypeScript(generated)) {
    throw new Error('Formatting-only generated contract differences must compare equal.');
  }

  if (canonicalizeTypeScript(styled) === canonicalizeTypeScript(changed)) {
    throw new Error('Real generated contract changes must compare different.');
  }

  console.log('Mithril OpenAPI contract comparison self-test passed.');
  return 0;
}

function run() {
  const tempDir = mkdtempSync(join(tmpdir(), 'instaclean-direct-mobile-openapi-'));
  const generatedPath = join(tempDir, 'mithril.ts');

  try {
    const result = spawnSync(
      'npx',
      ['--yes', 'openapi-typescript@7.13.0', source, '-o', generatedPath],
      {
        stdio: 'inherit',
        shell: process.platform === 'win32',
      },
    );

    if (result.error) throw result.error;
    if (result.status !== 0) return result.status ?? 1;

    const generated = readFileSync(generatedPath, 'utf8');
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    const isCurrent =
      current !== null && canonicalizeTypeScript(current) === canonicalizeTypeScript(generated);

    if (isCurrent) {
      console.log('Mithril generated types are up to date.');
      return 0;
    }

    if (checkOnly) {
      console.error(
        'Mithril generated types are stale. Run `npm run api:generate` and commit the result.',
      );
      return 1;
    }

    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, generated);
    console.log('Updated lib/mithril/generated/mithril.ts from Mithril OpenAPI.');
    return 0;
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    return 1;
  } finally {
    rmSync(tempDir, { recursive: true, force: true });
  }
}

try {
  process.exitCode = selfTest ? runSelfTest() : run();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
